import gradio as gr

def predict_skin(image):

    if image is None:
        return {}

    result = best_model.predict(
        source=image,
        imgsz=224,
        verbose=False
    )[0]

    scores = result.probs.data.cpu().numpy()

    top3 = scores.argsort()[::-1][:3]

    return {
        result.names[int(i)]: float(scores[i])
        for i in top3
    }

demo = gr.Interface(
    fn=predict_skin,

    inputs=gr.Image(
        type="pil",
        label="피부 사진 업로드"
    ),

    outputs=gr.Label(
        num_top_classes=3,
        label="피부질환 분류 결과"
    ),

    title="AI 피부질환 분류 서비스",

    description=(
        "AI Hub 피부종양 합성 데이터로 학습한 "
        "15종 이미지 분류 모델입니다. "
        "의학적 진단을 대신하지 않습니다."
    )
)

demo.launch(share=False)

