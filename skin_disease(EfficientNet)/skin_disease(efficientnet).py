def extract_zips_in_folder(source_dir, target_subfolder):
    target_dir = os.path.join(extract_path, target_subfolder)
    os.makedirs(target_dir, exist_ok=True)

    if os.path.exists(source_dir):
        files = os.listdir(source_dir)
        zip_files = [f for f in files if f.endswith('.zip')]

        if not zip_files:
            print(f"{source_dir} 폴더 내에 zip 파일이 존재하지 않습니다.")
            return

        for zip_file in zip_files:
            full_zip_path = os.path.join(source_dir, zip_file)
            print(f"Extracting {zip_file} to {target_dir}...")
            with zipfile.ZipFile(full_zip_path, 'r') as zip_ref:
                zip_ref.extractall(target_dir)
        print(f"{source_dir} extraction completed successfully.\n")
    else:
        print(f"경로를 찾을 수 없습니다: {source_dir}")

